"""
SUNTOWER-AI — Phase 3 prediction interface (STATUS: PLANNED, not demonstrated).

Target chosen: daily site energy consumption (kWh/day) per tower.
No lawful historical consumption labels exist in this repository, so no model
is trained or advertised. This module fixes the feature/label contract and a
leakage-resistant evaluation (temporal cut-off AND held-out sites) so that real
operator meter data can be dropped in later. Unit tests run it only on data
generated by make_synthetic_panel(), which is labelled SYNTHETIC.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import List, Optional, Sequence

import numpy as np
import pandas as pd

LABEL_CONTRACT = {
    "target": "energy_kwh_day",
    "target_unit": "kWh/day",
    "target_evidence_required": ("measured", "operator_supplied"),
    "keys": ("site_id", "date"),
    # Features must be known at prediction time; lagged target only from strictly earlier dates.
    "features": ("load_kw_nameplate", "tenants", "ghi_kwh_m2_day", "temp_c", "grid_hours_per_day",
                 "dow", "month", "lag7_mean"),
    "forbidden": ("diesel_l_per_day_same_day", "energy_kwh_day_same_day"),
}


@dataclass
class EvalReport:
    n_train: int
    n_test: int
    n_sites_train: int
    n_sites_test: int
    train_end: str
    test_start: str
    mae_baseline: float
    mae_model: Optional[float]
    model: str
    baseline: str
    data_label: str
    notes: List[str]


def add_lag_features(df: pd.DataFrame, target: str = "energy_kwh_day") -> pd.DataFrame:
    out = df.sort_values(["site_id", "date"]).copy()
    out["lag7_mean"] = (out.groupby("site_id")[target]
                        .transform(lambda s: s.shift(1).rolling(7, min_periods=3).mean()))
    out["dow"] = pd.to_datetime(out["date"]).dt.day_of_week
    out["month"] = pd.to_datetime(out["date"]).dt.month
    return out


def split_temporal_site(df: pd.DataFrame, cutoff: str, holdout_sites: Sequence[str]):
    """Train: dates < cutoff on non-holdout sites. Test: dates >= cutoff on holdout sites only."""
    d = pd.to_datetime(df["date"])
    train = df[(d < cutoff) & ~df["site_id"].isin(holdout_sites)]
    test = df[(d >= cutoff) & df["site_id"].isin(holdout_sites)]
    return train, test


def evaluate(df: pd.DataFrame, cutoff: str, holdout_sites: Sequence[str],
             data_label: str, features: Sequence[str] = LABEL_CONTRACT["features"],
             target: str = "energy_kwh_day", seed: int = 0) -> EvalReport:
    """Compare a moving-average baseline (lag7_mean) with gradient boosting on the same split."""
    from sklearn.ensemble import HistGradientBoostingRegressor

    data = add_lag_features(df, target).dropna(subset=["lag7_mean", target])
    leak = set(LABEL_CONTRACT["forbidden"]) & set(features)
    if leak:
        raise ValueError(f"Forbidden same-day features: {leak}")
    train, test = split_temporal_site(data, cutoff, holdout_sites)
    if train.empty or test.empty:
        raise ValueError("Empty train or test split")
    assert not set(train["site_id"]) & set(test["site_id"]), "site leakage"
    assert pd.to_datetime(train["date"]).max() < pd.to_datetime(test["date"]).min(), "time leakage"

    mae_base = float(np.mean(np.abs(test[target] - test["lag7_mean"])))
    feats = [f for f in features if f in data.columns]
    model = HistGradientBoostingRegressor(max_iter=200, learning_rate=0.05, random_state=seed)
    model.fit(train[feats], train[target])
    mae_model = float(np.mean(np.abs(test[target] - model.predict(test[feats]))))
    notes = []
    if mae_model >= mae_base:
        notes.append("Model does not beat the moving-average baseline; keep the simpler method.")
    return EvalReport(len(train), len(test), train["site_id"].nunique(), test["site_id"].nunique(),
                      str(pd.to_datetime(train["date"]).max().date()),
                      str(pd.to_datetime(test["date"]).min().date()),
                      mae_base, mae_model, "HistGradientBoostingRegressor", "7-day moving average",
                      data_label, notes)


def make_synthetic_panel(n_sites: int = 12, days: int = 240, seed: int = 7) -> pd.DataFrame:
    """SYNTHETIC panel for unit tests only. Values are invented and carry no evidential weight."""
    rng = np.random.default_rng(seed)
    dates = pd.date_range("2025-01-01", periods=days, freq="D")
    rows = []
    for i in range(n_sites):
        nameplate = rng.uniform(1.0, 3.5)
        tenants = int(rng.integers(1, 4))
        for d in dates:
            temp = 27 + 3 * np.sin(2 * np.pi * d.day_of_year / 365) + rng.normal(0, 1)
            ghi = 4.8 + 0.5 * np.cos(2 * np.pi * d.day_of_year / 365) + rng.normal(0, 0.3)
            e = 24 * nameplate * (0.7 + 0.08 * tenants) * (1 + 0.02 * (temp - 27)) + rng.normal(0, 1.5)
            rows.append({"site_id": f"SYN-{i:02d}", "date": d.date().isoformat(), "energy_kwh_day": e,
                         "load_kw_nameplate": nameplate, "tenants": tenants, "ghi_kwh_m2_day": ghi,
                         "temp_c": temp, "grid_hours_per_day": 12.0, "evidence_type": "synthetic"})
    return pd.DataFrame(rows)
